-- Preserve the official ballot numbering and expose it to contestants.
alter table public.pgws_contestants
  add column if not exists contestant_number integer;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'pgws_contestants_number_range'
      and conrelid = 'public.pgws_contestants'::regclass
  ) then
    alter table public.pgws_contestants
      add constraint pgws_contestants_number_range
      check (contestant_number is null or contestant_number between 1 and 999);
  end if;
end $$;

create unique index if not exists pgws_contestants_contestant_number_key
  on public.pgws_contestants(contestant_number)
  where contestant_number is not null;

